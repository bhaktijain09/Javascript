function info(name, age)  // function functionName(argument1, argument2)
{
console.log(`${name}'s age is ${age}!`)  // logic
}
info("Bhakti", 21); // functionName(parameter1, parameter2);
info("Jai", 19); // functionName(parameter1, parameter2);


// Arguments are the variable names listed in the function definition.
// Parameters are the actual values you pass into the function when calling it. 
// ie 
// Arguments - variable names in function definition
// Parameters - values passed in function calling.