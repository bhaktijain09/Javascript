// pre increment (++a;) ie first increment then use
let a = 26;
++a;
// output -  
// 27 increment
// 27 use
// so final used value is 27

// post increment (a++;) ie first use then increment
let b = 26;
b++;
// output -  
// 26 use
// 27 increment
// so final used value is 26


// pre decrement (--a;) ie first decrement then use
let c = 26;
--c;
// output -  
// 25 decrement
// 25 use
// so final used value is 25


// post decrement (a--;) ie first use then decrement
let d = 26;
d--;
// output - 
// 26 use 
// 25 decrement
// so final used value is 26


