let trafficcolor = "yellow";

switch (trafficcolor){
    case "red": 
    console.log("stop");
    break;
    case "yellow": 
    console.log("slow down");
    break;
    case "green": 
    console.log("go");
    break;
    default : 
    console.log("light is broken");
}

console.log("everything after switch statements can now be continued to be executed")