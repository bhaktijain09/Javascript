// print odd numbers from 0 to 10 
for(let i=1; i<=10; i+=2){ // starting (initialization value is imp) with 1(first odd number in range) and +2 after every iteration gives odd number
    console.log(i);
}
// output - 
// 1
// 3
// 5
// 7
// 9

// print odd numbers from 10 to 0 backwards
for(let i=9; i>=1; i-=2){ // starting (initialization value is imp) with 9(last odd number in range) and -2 after every iteration gives odd number backwards 
    console.log(i);
}